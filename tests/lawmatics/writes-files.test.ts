import { describe, it, expect, vi, afterEach } from "vitest";
import { addNote, setProspectCustomFields, uploadMatterFile, type FetchLike, type MultipartFetchLike } from "@/lib/lawmatics/writes";

/**
 * The Sprint 19 Lawmatics writers, with a fake fetch. The request shapes come from the public API
 * reference and are NOT verified against a live account, so the rule here is simple: every non-2xx
 * (and a thrown request) is "not done", every 2xx is "done" whatever the body says, and nothing
 * throws or logs what was sent.
 */

const DOCX = "application/vnd.openxmlformats-officedocument.wordprocessingml.document";
const BYTES = new Uint8Array([0x50, 0x4b, 3, 4, 1, 2, 3, 4, 5]);

function multipart(status = 200) {
  const calls: Array<{ url: string; method: string; headers: Record<string, string>; body: FormData }> = [];
  const fetchImpl: MultipartFetchLike = async (url, init) => {
    calls.push({ url, ...init });
    return { ok: status >= 200 && status < 300, status };
  };
  return { fetchImpl, calls };
}

function json(status = 200) {
  const calls: Array<{ url: string; method: string; headers: Record<string, string>; body: Record<string, unknown> }> = [];
  const fetchImpl: FetchLike = async (url, init) => {
    calls.push({ url, method: init.method, headers: init.headers, body: JSON.parse(init.body) });
    return { ok: status >= 200 && status < 300, status, json: async () => ({ echoed: "Sevetri Wilson" }), text: async () => "Sevetri Wilson sevetri@example.com" };
  };
  return { fetchImpl, calls };
}

afterEach(() => vi.restoreAllMocks());

describe("uploadMatterFile: POST /v1/files, multipart", () => {
  it("sends documentable_type, documentable_id, file and path[] with the bearer token and no Content-Type of its own", async () => {
    const { fetchImpl, calls } = multipart(201);
    const r = await uploadMatterFile("tok-org-1", { matterId: "LM-9", fileName: "Sevetri Wilson - Accepted Proposal.docx", mime: DOCX, bytes: BYTES }, fetchImpl);
    expect(r).toEqual({ ok: true });
    expect(calls).toHaveLength(1);
    const [call] = calls;
    expect(call.url).toBe("https://api.lawmatics.com/v1/files");
    expect(call.method).toBe("POST");
    expect(call.headers.Authorization).toBe("Bearer tok-org-1");
    // The boundary is generated by fetch from the FormData body: setting a Content-Type here would break it.
    expect(Object.keys(call.headers).map((h) => h.toLowerCase())).not.toContain("content-type");
    expect(call.body).toBeInstanceOf(FormData);

    const entries = [...call.body.entries()].map(([k]) => k);
    expect(entries.sort()).toEqual(["documentable_id", "documentable_type", "file", "path[]"]);
    expect(call.body.get("documentable_type")).toBe("matter");
    expect(call.body.get("documentable_id")).toBe("LM-9");
    expect(call.body.getAll("path[]")).toEqual(["Engagement"]);
    const file = call.body.get("file") as File;
    expect(file.name).toBe("Sevetri Wilson - Accepted Proposal.docx");
    expect(file.type).toBe(DOCX);
    expect(file.size).toBe(BYTES.length);
    expect(new Uint8Array(await file.arrayBuffer())).toEqual(BYTES);
  });

  it.each([200, 201, 202, 204])("every 2xx (%i) counts as uploaded, whatever the body", async (status) => {
    const { fetchImpl } = multipart(status);
    expect(await uploadMatterFile("t", { matterId: "1", fileName: "a.docx", mime: DOCX, bytes: BYTES }, fetchImpl)).toEqual({ ok: true });
  });

  it.each([
    [400, false],
    [401, false],
    [404, false],
    [422, false],
    [500, true],
    [429, true],
  ])("a %i is 'not uploaded' (retryable: %s) and never throws", async (status, retryable) => {
    const errors = vi.spyOn(console, "error").mockImplementation(() => {});
    const { fetchImpl } = multipart(status);
    const r = await uploadMatterFile("secret-token", { matterId: "1", fileName: "Sevetri.docx", mime: DOCX, bytes: BYTES }, fetchImpl);
    expect(r).toMatchObject({ ok: false, reason: `HTTP ${status}`, retryable, status });
    // Nothing that was sent is logged: no token, no file name, no ids.
    const logged = JSON.stringify(errors.mock.calls);
    for (const leak of ["secret-token", "Sevetri", "documentable"]) expect(logged).not.toContain(leak);
  });

  it("a thrown request is 'not uploaded' (retryable) and its message is kept out of the result and the log", async () => {
    const errors = vi.spyOn(console, "error").mockImplementation(() => {});
    const fetchImpl: MultipartFetchLike = async () => {
      throw new Error("ECONNRESET talking to api.lawmatics.com with token secret-token");
    };
    const r = await uploadMatterFile("secret-token", { matterId: "1", fileName: "a.docx", mime: DOCX, bytes: BYTES }, fetchImpl);
    expect(r).toEqual({ ok: false, reason: "request failed", retryable: true });
    expect(JSON.stringify(errors.mock.calls)).not.toContain("secret-token");
  });

  it("uses a different folder only when told to", async () => {
    const { fetchImpl, calls } = multipart();
    await uploadMatterFile("t", { matterId: "1", fileName: "a.docx", mime: DOCX, bytes: BYTES, path: "Billing" }, fetchImpl);
    expect(calls[0].body.getAll("path[]")).toEqual(["Billing"]);
  });
});

describe("addNote: POST /v1/notes", () => {
  it("sends a flat name, body, notable_type, notable_id and nothing else", async () => {
    const { fetchImpl, calls } = json();
    const r = await addNote("tok", { name: "Proposal accepted: Concierge", body: "Legal fee: $4,950\nUSPTO: $700", notableType: "Prospect", notableId: "LM-1" }, fetchImpl);
    expect(r).toEqual({ ok: true });
    const [call] = calls;
    expect(call.url).toBe("https://api.lawmatics.com/v1/notes");
    expect(call.method).toBe("POST");
    expect(call.headers.Authorization).toBe("Bearer tok");
    expect(Object.keys(call.body).sort()).toEqual(["body", "name", "notable_id", "notable_type"]);
    expect(call.body).toEqual({ name: "Proposal accepted: Concierge", body: "Legal fee: $4,950\nUSPTO: $700", notable_type: "Prospect", notable_id: "LM-1" });
  });

  it("a non-2xx is not-added, and Lawmatics' answer (which can echo the note) is never logged", async () => {
    const errors = vi.spyOn(console, "error").mockImplementation(() => {});
    const { fetchImpl } = json(422);
    const r = await addNote("tok", { name: "n", body: "b", notableType: "Prospect", notableId: "1" }, fetchImpl);
    expect(r).toMatchObject({ ok: false, reason: "HTTP 422", status: 422, retryable: false });
    expect(JSON.stringify(errors.mock.calls)).not.toContain("Sevetri");
    expect(JSON.stringify(errors.mock.calls)).not.toContain("sevetri@example.com");
  });

  it("a throw is not-added with a fixed reason", async () => {
    vi.spyOn(console, "error").mockImplementation(() => {});
    const r = await addNote("tok", { name: "n", body: "b", notableType: "Prospect", notableId: "1" }, async () => {
      throw new Error("boom for sevetri@example.com");
    });
    expect(r).toEqual({ ok: false, reason: "request failed", retryable: true });
  });
});

describe("setProspectCustomFields: PUT /v1/prospects/:id", () => {
  it("sends custom_fields [{id, value}] and no stage or tag key", async () => {
    const { fetchImpl, calls } = json();
    const r = await setProspectCustomFields("tok", "LM-77", [{ id: "301", value: "Concierge" }, { id: "302", value: "$4,950" }], fetchImpl);
    expect(r).toEqual({ ok: true });
    const [call] = calls;
    expect(call.url).toBe("https://api.lawmatics.com/v1/prospects/LM-77");
    expect(call.method).toBe("PUT");
    expect(Object.keys(call.body)).toEqual(["custom_fields"]);
    expect(call.body.custom_fields).toEqual([{ id: "301", value: "Concierge" }, { id: "302", value: "$4,950" }]);
    for (const forbidden of ["stage", "stage_id", "tags", "tag_ids", "status"]) expect(call.body).not.toHaveProperty(forbidden);
  });

  it("no fields means no request", async () => {
    const { fetchImpl, calls } = json();
    expect(await setProspectCustomFields("tok", "LM-77", [], fetchImpl)).toEqual({ ok: true });
    expect(calls).toHaveLength(0);
  });

  it("a non-2xx is not-written", async () => {
    vi.spyOn(console, "error").mockImplementation(() => {});
    const { fetchImpl } = json(500);
    expect(await setProspectCustomFields("tok", "1", [{ id: "1", value: "x" }], fetchImpl)).toMatchObject({ ok: false, retryable: true, status: 500 });
  });

  it("encodes an id that is not path-safe", async () => {
    const { fetchImpl, calls } = json();
    await setProspectCustomFields("tok", "a/b", [{ id: "1", value: "x" }], fetchImpl);
    expect(calls[0].url).toBe("https://api.lawmatics.com/v1/prospects/a%2Fb");
  });
});
